"""
pdf_extractor.py

Reads a "Coaching Agent Report" PDF (like the ones in static/uploads/)
and pulls out the structured fields we care about:

    - agent_id, agent_name
    - call_id
    - role
    - evaluation_date
    - csat_score, csat_target
    - fcr_percent, fcr_target_percent          (First Contact Resolution)
    - aht_seconds, aht_display, aht_target_seconds   (Avg Handling Time)
    - quality_rating_percent, quality_target_percent
    - weaknesses (list of strings)

Any numeric field that can't be found in the PDF is returned as 0
(never None / never crashes), per the "count missing as zero" rule.

Usage:
    from pdf_extractor import extract_report_data
    data = extract_report_data("static/uploads/some_report.pdf")
"""

import re
from pathlib import Path

import pdfplumber


def _to_number(raw: str) -> float:
    """Turn '3.6' or '64%' or '' into a float. Defaults to 0."""
    if not raw:
        return 0.0
    match = re.search(r"[-+]?\d*\.?\d+", raw)
    if not match:
        return 0.0
    try:
        return float(match.group())
    except ValueError:
        return 0.0


def _mmss_to_seconds(raw: str) -> int:
    """Turn '14m 20s' into 860. Defaults to 0."""
    if not raw:
        return 0
    minutes = re.search(r"(\d+)\s*m", raw)
    seconds = re.search(r"(\d+)\s*s", raw)
    total = 0
    if minutes:
        total += int(minutes.group(1)) * 60
    if seconds:
        total += int(seconds.group(1))
    return total


def extract_report_data(pdf_path: str) -> dict:
    """
    Extract all useful fields from a coaching report PDF.
    Returns a plain dict, ready to be inserted into Supabase.
    Never raises on missing fields -- missing numbers become 0,
    missing text becomes "".
    """
    pdf_path = Path(pdf_path)

    full_text = ""
    with pdfplumber.open(pdf_path) as pdf:
        for page in pdf.pages:
            page_text = page.extract_text() or ""
            full_text += page_text + "\n"

    data = {
        "source_file": pdf_path.name,
        "agent_id": "",
        "agent_name": "",
        "call_id": "",
        "role": "",
        "evaluation_date": "",
        "csat_score": 0.0,
        "csat_target": 0.0,
        "fcr_percent": 0.0,
        "fcr_target_percent": 0.0,
        "aht_seconds": 0,
        "aht_display": "",
        "aht_target_seconds": 0,
        "quality_rating_percent": 0.0,
        "quality_target_percent": 0.0,
        "weaknesses": [],
    }

    # ---- Agent Name & ID, e.g. "Agent 001 - Alex Morgan" ----
    # Stop the name capture right before the Call ID (e.g. "C-849201") starts.
    m = re.search(r"Agent\s+(\d+)\s*-\s*([A-Za-z .']+?)(?=\s*C-\d)", full_text)
    if not m:
        # fallback if there's no Call ID right after the name
        m = re.search(r"Agent\s+(\d+)\s*-\s*([A-Za-z .']+)", full_text)
    if m:
        data["agent_id"] = m.group(1).strip()
        data["agent_name"] = m.group(2).strip()

    # ---- Call ID, e.g. "C-849201" ----
    m = re.search(r"\bC-\d+\b", full_text)
    if m:
        data["call_id"] = m.group(0)

    # ---- Role: text between Call ID and the date on the header line ----
    m = re.search(r"C-\d+\s+(.+?)\s+([A-Z][a-z]+ \d{1,2}, \d{4})", full_text)
    if m:
        data["role"] = m.group(1).strip()
        data["evaluation_date"] = m.group(2).strip()

    # ---- CSAT Score, e.g. "CSAT Score 3.6 / 5.0 Target: 4.5" ----
    m = re.search(r"CSAT Score\s+([\d.]+)\s*/\s*([\d.]+)\s+Target:\s*([\d.]+)", full_text)
    if m:
        data["csat_score"] = _to_number(m.group(1))
        data["csat_target"] = _to_number(m.group(3))

    # ---- First Contact Resolution, e.g. "First Contact Resolution 64% Target: 80%" ----
    m = re.search(r"First Contact Resolution\s+([\d.]+)%\s+Target:\s*([\d.]+)%", full_text)
    if m:
        data["fcr_percent"] = _to_number(m.group(1))
        data["fcr_target_percent"] = _to_number(m.group(2))

    # ---- Avg Handling Time, e.g. "Avg Handling Time 14m 20s Target: 10m 00s" ----
    m = re.search(r"Avg Handling Time\s+([0-9ms ]+?)\s+Target:\s*([0-9ms ]+)", full_text)
    if m:
        aht_raw = m.group(1).strip()
        target_raw = m.group(2).strip()
        data["aht_display"] = aht_raw
        data["aht_seconds"] = _mmss_to_seconds(aht_raw)
        data["aht_target_seconds"] = _mmss_to_seconds(target_raw)

    # ---- Quality Audit Rating, e.g. "Quality Audit Rating 72% Target: 88%" ----
    m = re.search(r"Quality Audit Rating\s+([\d.]+)%\s+Target:\s*([\d.]+)%", full_text)
    if m:
        data["quality_rating_percent"] = _to_number(m.group(1))
        data["quality_target_percent"] = _to_number(m.group(2))

    # ---- Weaknesses: bullet points under "Main Identified Weaknesses" ----
    weakness_block = re.search(
        r"Main Identified Weaknesses\s*(.+?)(?:Generated by|$)", full_text, re.DOTALL
    )
    if weakness_block:
        lines = weakness_block.group(1).split("\n")
        for line in lines:
            line = line.strip().lstrip("•").strip()
            if line:
                data["weaknesses"].append(line)

    return data


if __name__ == "__main__":
    # Quick manual test against the sample files already in static/uploads/
    import json
    import sys

    upload_dir = Path(__file__).parent / "static" / "uploads"
    pdfs = list(upload_dir.glob("*.pdf")) if len(sys.argv) < 2 else [Path(sys.argv[1])]

    for pdf in pdfs:
        print(f"\n=== {pdf.name} ===")
        result = extract_report_data(str(pdf))
        print(json.dumps(result, indent=2))